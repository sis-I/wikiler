"""Acceptance checks for the committed sanitized example vault.

The fixture is a human-readable example and a CI target. Every test copies it
into a temporary directory before running a command, so no test ever writes to
the committed fixture. Assertions are structural and string-based: they prove
shape and absence, never the meaning of the authored prose.
"""

import contextlib
import hashlib
import io
import json
import os
import re
import shutil
import tempfile
import unittest
from pathlib import Path

from wikiler.cli import main


REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE = REPO_ROOT / "examples" / "vault"
RUNTIME_RULES = REPO_ROOT / "src" / "wikiler" / "runtime_rules.md"

PAGE_DIRS = ("sources", "entities", "concepts", "synthesis", "queries")

# Known-good page set and titles from the acceptance contract. Expected values
# are literals, not values recomputed from the files under test.
EXPECTED_PAGES = {
    "sources/tidal-sorting.md": "Tidal Sorting",
    "sources/quiet-protocol.md": "Quiet Protocol",
    "entities/lumen-council.md": "Lumen Council",
    "concepts/marker-decay.md": "Marker Decay",
    "concepts/quiet-consensus.md": "Quiet Consensus",
    "synthesis/tidal-quiet-comparison.md": "Tidal Quiet Comparison",
    "queries/marker-decay-question.md": "Marker Decay Question",
}

EXPECTED_DIRS = (
    "raw/articles",
    "raw/papers",
    "raw/repos",
    "raw/datasets",
    "raw/assets",
    "wiki",
    "wiki/sources",
    "wiki/entities",
    "wiki/concepts",
    "wiki/synthesis",
    "wiki/queries",
    "output",
)

SANITIZATION_PATTERNS = {
    "email address": r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}",
    "absolute user path": r"/Users/",
    "private vault name": r"pi-wiki-vault",
    "maintainer handle": r"sis-I",
    "URL": r"https?://",
}


def _snapshot(root):
    """Hash every file under *root* so byte-level changes are detectable."""
    root = Path(root)
    return {
        path.relative_to(root).as_posix(): hashlib.sha256(
            path.read_bytes()
        ).hexdigest()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


class ExampleVaultAcceptance(unittest.TestCase):
    def setUp(self):
        old = os.environ.get("WIKI_VAULT")
        os.environ.pop("WIKI_VAULT", None)
        self._old_env = old

    def tearDown(self):
        if self._old_env is None:
            os.environ.pop("WIKI_VAULT", None)
        else:
            os.environ["WIKI_VAULT"] = self._old_env

    def _run(self, vault, *argv):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = main(["--vault", str(vault), *argv])
        return rc, buf.getvalue()

    def _copy_fixture(self, parent):
        dest = Path(parent) / "vault"
        shutil.copytree(FIXTURE, dest)
        return dest

    def test_fixture_shape_and_sanitization(self):
        with tempfile.TemporaryDirectory() as tmp:
            fixture = self._copy_fixture(tmp)
            self.assertTrue(fixture.is_dir())
            self.assertFalse(
                (fixture / ".obsidian").exists(),
                "no Obsidian config may be committed",
            )

            # The fixture consumed the rules regenerated by the vault-contract
            # ticket: the example AGENTS.md is a byte-for-byte copy.
            self.assertEqual(
                (fixture / "AGENTS.md").read_bytes(),
                RUNTIME_RULES.read_bytes(),
            )

            pages = {
                path.relative_to(fixture / "wiki").as_posix()
                for sub in PAGE_DIRS
                for path in (fixture / "wiki" / sub).glob("*.md")
            }
            self.assertEqual(pages, set(EXPECTED_PAGES))

            raw_files = {
                path.relative_to(fixture / "raw").as_posix()
                for path in (fixture / "raw").rglob("*")
                if path.is_file()
            }
            self.assertEqual(
                raw_files,
                {
                    "articles/tidal-sorting.md",
                    "papers/quiet-protocol.md",
                    "assets/tidal-chart.png",
                },
            )
            self.assertTrue((fixture / "output" / "example-output.md").is_file())

            index = (fixture / "wiki" / "index.md").read_text(encoding="utf-8")
            for rel, title in EXPECTED_PAGES.items():
                text = (fixture / "wiki" / rel).read_text(encoding="utf-8")
                self.assertNotIn("TODO", text, f"unfilled marker in {rel}")
                for field in (
                    "type:", "title:", "sources:",
                    "created:", "updated:", "tags:",
                ):
                    self.assertIn(field, text, f"missing frontmatter field in {rel}")
                self.assertIn(f"# {title}", text, f"H1 mismatch in {rel}")
                self.assertIn(
                    f"- [[{rel[:-3]}|{title}]]", index, f"not linked from index: {rel}"
                )

            output = (fixture / "output" / "example-output.md").read_text(
                encoding="utf-8"
            )
            self.assertIn("[[sources/tidal-sorting|Tidal Sorting]]", output)

            # String absence only: no prose is read for meaning. Binary assets
            # are skipped, every text file in the fixture is scanned.
            for path in fixture.rglob("*"):
                if not path.is_file() or path.suffix not in (".md",):
                    continue
                text = path.read_text(encoding="utf-8")
                for label, pattern in SANITIZATION_PATTERNS.items():
                    self.assertNotRegex(
                        text, pattern, f"{label} found in {path}"
                    )
                self.assertNotIn("\u2014", text, f"em dash in {path}")
                self.assertNotIn("\u2013", text, f"en dash in {path}")

    def test_init_acceptance(self):
        with tempfile.TemporaryDirectory() as tmp:
            vault = Path(tmp) / "fresh"
            vault.mkdir()

            rc, _out = self._run(vault, "init")
            self.assertEqual(rc, 0)
            for rel in EXPECTED_DIRS:
                self.assertTrue((vault / rel).is_dir(), f"missing dir: {rel}")
            self.assertTrue((vault / "wiki" / "index.md").is_file())
            self.assertTrue((vault / "wiki" / "log.md").is_file())
            log_text = (vault / "wiki" / "log.md").read_text(encoding="utf-8")
            self.assertEqual(log_text.count("setup |"), 1)

            before = _snapshot(vault)
            rc, _out = self._run(vault, "init")
            self.assertEqual(rc, 0)
            self.assertEqual(_snapshot(vault), before, "re-init must be a no-op")
            self.assertEqual(
                (vault / "wiki" / "log.md").read_text(encoding="utf-8").count(
                    "setup |"
                ),
                1,
            )

            for index, argv in enumerate(
                (
                    ("ingest", "x.md"),
                    ("query", "question"),
                    ("lint",),
                    ("lint", "--fix"),
                    ("sync",),
                )
            ):
                empty = Path(tmp) / f"non_vault_{index}"
                empty.mkdir()
                with self.subTest(argv=argv):
                    rc, _out = self._run(empty, *argv)
                    self.assertEqual(rc, 1)
                    self.assertEqual(list(empty.rglob("*")), [])

    def test_ingest_acceptance(self):
        with tempfile.TemporaryDirectory() as tmp:
            vault = self._copy_fixture(tmp)
            # Add a fresh source to the temp copy so ingest creates a page.
            (vault / "raw" / "articles" / "harbor-lamp.md").write_text(
                "---\ntitle: Harbor Lamp\ntags: [lamp]\n---\n\n"
                "# Harbor Lamp\n\n![[tidal-chart.png]]\nA shared fixture chart.\n",
                encoding="utf-8",
            )
            assets_before = set((vault / "raw" / "assets").iterdir())
            before = _snapshot(vault)

            rc, out = self._run(
                vault, "ingest", "articles/harbor-lamp.md", "--json"
            )
            self.assertEqual(rc, 0)
            manifest = json.loads(out)
            self.assertEqual(
                set(manifest),
                {"source", "page", "title", "created", "todos", "images"},
            )
            self.assertEqual(manifest["source"], "raw/articles/harbor-lamp.md")
            self.assertEqual(manifest["page"], "wiki/sources/harbor-lamp.md")
            self.assertEqual(manifest["title"], "Harbor Lamp")
            self.assertTrue(manifest["created"])
            self.assertIn("Key claims", manifest["todos"])
            self.assertEqual(manifest["images"], 1)

            page = vault / "wiki" / "sources" / "harbor-lamp.md"
            self.assertTrue(page.is_file())
            self.assertIn("<!-- TODO:", page.read_text(encoding="utf-8"))

            after = _snapshot(vault)
            changed = {
                rel
                for rel in set(before) | set(after)
                if before.get(rel) != after.get(rel)
            }
            self.assertEqual(
                changed,
                {
                    "wiki/index.md",
                    "wiki/log.md",
                    "wiki/sources/harbor-lamp.md",
                },
            )
            for rel, digest in before.items():
                if rel.startswith("raw/"):
                    self.assertEqual(after.get(rel), digest)
            self.assertEqual(set((vault / "raw" / "assets").iterdir()), assets_before)
            self.assertIn(
                "- [[sources/harbor-lamp|Harbor Lamp]]",
                (vault / "wiki" / "index.md").read_text(encoding="utf-8"),
            )
            self.assertEqual(
                (vault / "wiki" / "log.md").read_text(encoding="utf-8").count(
                    "ingest | Harbor Lamp"
                ),
                1,
            )

            # Force preserves an existing created date while restoring TODOs.
            original = page.read_text(encoding="utf-8")
            self.assertRegex(original, r"(?m)^created: \d{4}-\d{2}-\d{2}$")
            page.write_text(
                re.sub(r"(?m)^created: .*$", "created: 2020-01-01", original),
                encoding="utf-8",
            )
            rc, out = self._run(
                vault, "ingest", "articles/harbor-lamp.md", "--json", "--force"
            )
            self.assertEqual(rc, 0)
            self.assertFalse(json.loads(out)["created"])
            forced = page.read_text(encoding="utf-8")
            self.assertIn("created: 2020-01-01", forced)
            self.assertIn("<!-- TODO:", forced)

    def test_query_acceptance(self):
        with tempfile.TemporaryDirectory() as tmp:
            vault = self._copy_fixture(tmp)
            before = _snapshot(vault)
            question = "Quiet Consensus"

            rc, out = self._run(vault, "query", question, "--json")
            self.assertEqual(rc, 0)
            data = json.loads(out)
            self.assertEqual(data["question"], question)
            matches = data["matches"]
            self.assertTrue(matches)
            self.assertEqual(matches[0]["target"], "concepts/quiet-consensus")
            for match in matches:
                self.assertEqual(
                    set(match), {"target", "title", "path", "snippet"}
                )

            rc, human = self._run(vault, "query", question)
            self.assertEqual(rc, 0)
            self.assertIn("Candidates (", human)
            self.assertIn("1. [[concepts/quiet-consensus|Quiet Consensus]]", human)
            self.assertEqual(_snapshot(vault), before)

    def test_lint_acceptance(self):
        with tempfile.TemporaryDirectory() as tmp:
            vault = self._copy_fixture(tmp)
            clean = {"errors": 0, "warnings": 0, "info": 0}

            rc, out = self._run(vault, "lint", "--json")
            self.assertEqual(rc, 0)
            data = json.loads(out)
            self.assertEqual(data["command"], "lint")
            self.assertEqual(data["summary"], clean)
            self.assertEqual(data["findings"], [])

            rc, human = self._run(vault, "lint")
            self.assertEqual(rc, 0)
            self.assertIn("Lint passed: no issues found.", human)

            before = _snapshot(vault)
            rc, out = self._run(vault, "lint", "--fix", "--json")
            self.assertEqual(rc, 0)
            data = json.loads(out)
            self.assertEqual(data["summary"], clean)
            self.assertEqual(data["fixes"]["files_changed"], [])
            self.assertEqual(data["fixes"]["links_rewritten"], [])
            self.assertEqual(_snapshot(vault), before)

    def test_sync_acceptance(self):
        with tempfile.TemporaryDirectory() as tmp:
            vault = self._copy_fixture(tmp)
            before = _snapshot(vault)

            rc, out = self._run(vault, "sync")
            self.assertEqual(rc, 0)
            self.assertIn("sync: nothing to do", out)
            self.assertEqual(_snapshot(vault), before)
            self.assertEqual(
                (vault / "wiki" / "log.md").read_text(encoding="utf-8").count(
                    "setup |"
                ),
                1,
            )


if __name__ == "__main__":
    unittest.main()
